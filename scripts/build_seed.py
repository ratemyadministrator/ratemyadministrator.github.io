"""Turn researched administrator lists into a SQL file you can paste into Supabase.

    python scripts/build_seed.py data/admins/*.json > seed/admins.sql

Each input file is a JSON array of
  {"instId", "name", "title", "level", "sourceUrl", "checked"}
Institution names are looked up in data/directory.json. Rows that already
exist (same institution, same name) are skipped, so re-running is safe.
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
inst = {r[0]: r[1] for r in json.load(open(ROOT / "data" / "directory.json"))["inst"]}
LEVELS = {"board", "exec", "vp", "dean", "director"}

def q(v):
    return "null" if v in (None, "") else "'" + str(v).replace("'", "''") + "'"

seen, skipped = {}, []
for path in sys.argv[1:]:
    for a in json.load(open(path)):
        name = re.sub(r"\s+", " ", re.sub(r"^(Dr\.?|Mr\.?|Ms\.?|Mrs\.?)\s+", "", (a.get("name") or "").strip()))
        name = re.sub(r",\s*(Ph\.?D\.?|Ed\.?D\.?|J\.?D\.?|M\.?D\.?|D\.?P\.?A\.?)\.?$", "", name).strip()
        title = (a.get("title") or "").strip()[:160]
        if a.get("instId") not in inst or len(name) < 5 or len(name) > 80 or len(title) < 3 or a.get("level") not in LEVELS:
            skipped.append(a); continue
        key = (a["instId"], name.lower())
        rank = ["board", "exec", "vp", "dean", "director"].index(a["level"])
        if key in seen:  # same person, second title: combine them, keep the higher level
            r = seen[key]
            if title.lower() not in r["title"].lower():
                r["title"] = (r["title"] + " / " + title)[:160]
            if rank < r["rank"]:
                r["rank"], r["level"] = rank, a["level"]
            continue
        seen[key] = {"name": name, "title": title, "level": a["level"], "rank": rank, "inst": a["instId"],
                     "src": a.get("sourceUrl"), "checked": a.get("checked")}

rows = [f"({q(r['name'])},{q(r['title'])},{q(r['level'])},{q(r['inst'])},{q(inst[r['inst']])},{q(r['src'])},{q(r['checked'])})"
        for r in seen.values()]

print("-- Generated by scripts/build_seed.py. Paste into Supabase > SQL Editor and click Run.")
print(f"-- {len(rows)} administrators")
for i in range(0, len(rows), 500):
    print("insert into public.admins (name, title, level, inst_id, inst_name, source_url, checked_on) values")
    print(",\n".join(rows[i:i + 500]))
    print("on conflict do nothing;")
print(f"Skipped {len(skipped)} malformed rows", file=sys.stderr)
